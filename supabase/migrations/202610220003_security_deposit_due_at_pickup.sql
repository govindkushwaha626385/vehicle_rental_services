-- 202610220003_security_deposit_due_at_pickup.sql
-- The refundable security deposit is collected in person at pick-up. It is not
-- a Razorpay card pre-authorisation, so we no longer write simulated
-- "authorized" payment rows for it.
--
-- Snapshot the amount on each booking, backfill existing bookings from the
-- current policy, remove the fake hold rows, and keep them out of booking_json
-- so old records cannot surface as card transactions.

alter table public.bookings
  add column if not exists hold_amount integer;

update public.bookings
set hold_amount = coalesce(
  (select nullif(value, '')::integer from public.settings where key = 'hold_amount'),
  5000
)
where hold_amount is null;

create or replace function public.default_hold_amount()
returns integer
language sql
stable
set search_path = public
as $$
  select coalesce(
    (select nullif(value, '')::integer from public.settings where key = 'hold_amount'),
    5000
  );
$$;

alter table public.bookings
  alter column hold_amount set default public.default_hold_amount();

alter table public.bookings
  alter column hold_amount set not null;

alter table public.bookings
  drop constraint if exists bookings_hold_amount_valid;
alter table public.bookings
  add constraint bookings_hold_amount_valid check (hold_amount between 0 and 1000000);

-- These were generated by the old checkout/webhook code. No money moved, so
-- they must not remain in the payment ledger or accounting exports.
delete from public.payments where kind = 'hold';

create or replace function public.booking_json(p_booking_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'id', b.id,
    'code', b.code,
    'status', b.status,
    'paymentStatus', b.payment_status,
    'paymentPlan', b.payment_plan,
    'pickupLocation', b.pickup_location,
    'dropoffLocation', b.dropoff_location,
    'startDate', b.start_date,
    'endDate', b.end_date,
    'pickupTime', b.pickup_time,
    'dropoffTime', b.dropoff_time,
    'days', b.days,
    'extras', coalesce((
      select jsonb_agg(jsonb_build_object('key', e.key, 'label', e.label, 'pricePerDay', e.price_per_day) order by e.id)
      from unnest(b.extras) as k(key)
      join public.extras e on e.key = k.key
    ), '[]'::jsonb),
    'extraKeys', to_jsonb(b.extras),
    'insurance', jsonb_build_object(
      'key', b.insurance,
      'label', coalesce(it.label, initcap(b.insurance)),
      'pricePerDay', coalesce(it.price_per_day, 0),
      'deductible', coalesce(it.deductible, 0),
      'blurb', coalesce(it.blurb, '')
    ),
    'baseTotal', b.base_total,
    'extrasTotal', b.extras_total,
    'insuranceTotal', b.insurance_total,
    'oneWayFee', b.one_way_fee,
    'fees', b.fees,
    'taxRate', b.tax_rate,
    'taxInclusive', b.tax_inclusive,
    'discount', b.discount,
    'total', b.total,
    'depositDue', b.deposit_due,
    'amountPaid', b.amount_paid,
    'balanceDue', greatest(0, b.total - b.amount_paid),
    'promoCode', b.promo_code,
    'driver', jsonb_build_object(
      'name', b.driver_name,
      'email', b.driver_email,
      'phone', b.driver_phone,
      'license', b.driver_license,
      'dob', b.driver_dob
    ),
    'notes', b.notes,
    'createdAt', b.created_at,
    'cancelledAt', b.cancelled_at,
    'cancellationReason', b.cancellation_reason,
    'cancelledBy', b.cancelled_by,
    'pickupAt', (b.start_date::text || 'T' || b.pickup_time || ':00'),
    'holdAmount', b.hold_amount,
    'vehicle', jsonb_build_object(
      'id', v.id,
      'name', v.name,
      'brand', v.brand,
      'type', v.type,
      'imageUrl', v.image_url,
      'pricePerDay', v.price_per_day,
      'location', v.location
    ),
    'customer', jsonb_build_object(
      'name', coalesce(p.full_name, b.guest_name),
      'email', coalesce(p.email, b.guest_email),
      'phone', coalesce(p.phone, b.guest_phone),
      'isGuest', b.user_id is null
    ),
    'reviewed', exists(select 1 from public.reviews r where r.booking_id = b.id),
    'canCancel', b.status in ('pending','confirmed')
      and (b.start_date + b.pickup_time::time) > (now() at time zone 'Asia/Kolkata'),
    'canReview', b.status = 'completed' and b.user_id is not null
      and not exists(select 1 from public.reviews r where r.booking_id = b.id),
    'payments', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', pay.id, 'kind', pay.kind, 'amount', pay.amount, 'status', pay.status,
        'brand', pay.brand, 'last4', pay.last4, 'reference', pay.reference, 'createdAt', pay.created_at
      ) order by pay.created_at)
      from public.payments pay
      where pay.booking_id = b.id and pay.kind <> 'hold'
    ), '[]'::jsonb)
  )
  from public.bookings b
  join public.vehicles v on v.id = b.vehicle_id
  left join public.insurance_tiers it on it.key = b.insurance
  left join public.profiles p on p.id = b.user_id
  where b.id = p_booking_id;
$$;

revoke all on function public.booking_json(uuid) from public, anon, authenticated;
